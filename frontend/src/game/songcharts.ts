export const trackById = (id: string): TrackDef | undefined => TRACKS.find((t) => t.id === id);

/** 이 싱글이 음원 곡이면 그 곡. */
export const trackOfSingle = (single: Pick<Single, 'title' | 'persona'> | undefined): TrackDef | null =>
  (single && TRACKS.find((t) => t.title === single.title && t.persona === single.persona)) || null;

/** 발매한 싱글 가운데 리듬 모드로 플레이할 수 있는 것(음원 곡뿐이다). */
export const trackSingles = <T extends Pick<Single, 'title' | 'persona'>>(singles: readonly T[]): T[] => singles.filter((s) => trackOfSingle(s));

/** 지금 하고 있는 리듬 실행이 음원 곡이면 그 곡. */
export const trackOfRun = (singles: readonly Pick<Single, 'id' | 'title' | 'persona'>[], run: { kind: string; target: string | null } | null | undefined): TrackDef | null =>
  run && run.kind === 'rhythm' && run.target ? trackOfSingle(singles.find((s) => s.id === run.target)) : null;

/** 16분음표 한 칸(ms) */
export const slotMs = (t: Pick<TrackDef, 'bpm'>): number => 60_000 / t.bpm / 4;
