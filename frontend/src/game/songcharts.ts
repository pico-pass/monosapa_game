import type { RhythmLevel } from './arcade';
import type { Persona, Single } from './types';

/*
 * 음원이 있는 리듬 곡. 음원 한 곡에 채보를 직접 박아 둔다(곡 번호로 자동 생성하는 채보와 다르다).
 * 채보는 음원을 분석해서 만들었다: 140 BPM이 일정한 곡이라 첫 박 위치(firstBeatMs)와 16분음표 격자에 노트를 맞췄고,
 * 저음·중음·고음 어택의 세기로 격자 위치를 골랐다(난이도별 밀도만 다르다). 음원 파일은 public/assets, 재생은 audio/track.ts.
 *
 * 노트 하나는 슬롯 × 4 + 레인 하나의 수다. 슬롯은 첫 박부터 센 16분음표 번호(0, 1, 2…)이고, 음원 시각은
 *   firstBeatMs + 슬롯 × 60000 / bpm / 4  (게임 시각은 여기에 leadInMs를 더한다)
 */

export interface TrackDef {
  id: string;
  /** 이 제목의 싱글만 음원으로 플레이한다 */
  title: string;
  /** 싱글을 발매한 자아 */
  persona: Persona;
  bpm: number;
  /** 음원 0초에서 첫 박(슬롯 0)까지 */
  firstBeatMs: number;
  /** 음원을 처음부터 이만큼만 재생한다 */
  playMs: number;
  /** 끝에서 이만큼 서서히 줄인다 */
  fadeMs: number;
  notes: Record<RhythmLevel, readonly number[]>;
}

